// Copies runtime support files into public/. GLBs are produced per tier by scripts/compress.mjs.
import { cpSync, mkdirSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('../../', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const app = join(root, 'app')
const pub = join(app, 'public')
const copyDir = (from, to, filter = () => true) => {
  mkdirSync(to, { recursive: true })
  for (const f of readdirSync(from).filter(filter)) {
    cpSync(join(from, f), join(to, f))
    console.log(to.replace(pub, 'public'), f)
  }
}

// runtime textures loaded outside the GLBs (album art for the console plaque, vinyl anisotropy direction)
copyDir(join(root, 'blender/textures'), join(pub, 'assets/textures'), (f) => /^JT_(Cover_\d+|Vinyl_Anisotropy)\.png$/.test(f))
// custom wordmark (generated by blender/scripts/jt_letters.py)
copyDir(join(root, 'assets/brand'), join(pub, 'assets/brand'), (f) => f.endsWith('.svg'))
// self-hosted decoders: Draco geometry + Basis Universal (KTX2) transcoder
copyDir(join(app, 'node_modules/three/examples/jsm/libs/draco/gltf'), join(pub, 'draco'))
copyDir(join(app, 'node_modules/three/examples/jsm/libs/basis'), join(pub, 'basis'))
